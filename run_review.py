#
# Применяется, когда Review Pack не содержит policy.yaml — то есть для
# пакетов, выпущенных до 06.09.2026, и при запуске ядра с голым
# идентификатором пакета вместо каталога.
#
# Значения ДОСЛОВНО повторяют текст промпта, на котором сняты метрики
# (полнота 88% по месту / 77% по типу). Менять их здесь нельзя: политика —
# это версионируемый артефакт пакета, а не константа кода. Ради этого
# правила файл review-packs/mts-net/0.2/policy.yaml и существует.
# Слой семантической верификации по умолчанию.
#
# mode=advisory намеренно: слой ВЫНОСИТ суждение и кладёт его в результат,
# но выдачу не меняет. Причина в порядке действий, а не в осторожности —
# цену независимой проверки нельзя измерить, если она сразу же начинает
# менять то, что измеряют. Сначала замер (сколько отвергнуто и справедливо
# ли), потом решение о включении enforcing, и это решение — версия пакета.
DEFAULT_VERIFICATION = {
    "mode": "advisory",     # off | advisory | enforcing
    "batch_size": 8,        # замечаний в одном вызове верификатора
}

DEFAULT_POLICY = {
    "ceiling": BUDGET_CEILING,
    "bias": "recall",
    "verification": dict(DEFAULT_VERIFICATION),
    "prompt": {
        "bias": "Полнота важнее осторожности. Пропущенная проблема хуже "
                "лишней придирки. Сомневаешься — выдавай.",
        "fragment_quota": "Ориентир: от пяти до десяти замечаний на фрагмент. "
                          "Меньше пяти — скорее всего ты не дошёл до конца "
                          "списка типов.",
        "document_quota": "Ориентир: от двух до шести замечаний на документ. "
                          "Это дополнительный проход, основные дефекты уже "
                          "найдены отдельно.",
    },
}

POLICY_PROMPT_KEYS = ("bias", "fragment_quota", "document_quota")
POLICY_BIAS_VALUES = ("recall", "precision", "balanced")


class PolicyInvalid(Exception):
    """Политика пакета не пригодна к применению.

    Отдельный тип, а не общий ValueError: docreview превращает его
    в REVIEW_PACK_INVALID с retriable=false — повторять запуск бессмысленно,
    чинить надо пакет.
    """


POLICY_TOP_KEYS = ("ceiling", "bias", "prompt", "verification")
POLICY_VERIFICATION_KEYS = ("mode", "batch_size")
POLICY_VERIFICATION_MODES = ("off", "advisory", "enforcing")


def _names(keys):
    """Имена ключей для сообщения об ошибке, устойчиво к их типу.

    YAML разрешает нестроковые ключи (`1:`, `true:`, `[a]:`), и прямой
    `sorted(...)` на смешанном множестве падает TypeError. Падение здесь —
    не косметика: PolicyInvalid превращается в REVIEW_PACK_INVALID (exit 4),
    а TypeError уходит в общий обработчик и становится INTERNAL_ERROR,
    то есть ошибка ПАКЕТА выглядела бы как поломка ядра.
    """
    return ", ".join(sorted(repr(k) for k in keys))


def load_policy(path=None):
    """Политика приёмки из policy.yaml пакета; без файла — DEFAULT_POLICY.

    ЛИБО ФАЙЛА НЕТ, ЛИБО ОН ПОЛНЫЙ. Частичная политика не поддерживается,
    и это не строгость ради строгости. Наследование недостающих полей из
    DEFAULT_POLICY возвращало ровно ту проблему, ради которой файл заведён:

      - `ceilling: 5` (опечатка) молча давал потолок 20 — пакет объявляет
        одно, ядро делает другое;
      - `bias: precision` без `prompt.bias` публиковал в результате
        «precision», отправляя модели recall-текст «сомневаешься — выдавай».
        Метка политики и применённая политика расходились, и наружу уходила
        первая.

    Поэтому: файла нет — работают умолчания (так живут пакеты, выпущенные
    до 06.09.2026). Файл есть — он объявляет политику целиком, иначе это
    ошибка пакета. Умолчания при наличии файла не подмешиваются никогда.
    """
    if not path:
        return copy.deepcopy(DEFAULT_POLICY)
    try:
        raw = yaml.safe_load(open(path, encoding="utf-8"))
    except Exception as e:                          # noqa: BLE001
        raise PolicyInvalid("политика %s не читается: %s" % (path, e))
    # Ни `or {}`, ни мягкой проверки: пустой файл, null, список и false
    # иначе становились бы пустым словарём и тихо откатывались на умолчания.
    if not isinstance(raw, dict):
        raise PolicyInvalid(
            "политика %s: ожидался словарь с ключами %s, получено %s. "
            "Пустой или сломанный файл политики — ошибка пакета: молчаливый "
            "откат на умолчания означал бы прогон не по той политике, "
            "которая записана в пакете."
            % (path, ", ".join(POLICY_TOP_KEYS), type(raw).__name__))

    unknown = set(raw) - set(POLICY_TOP_KEYS)
    if unknown:
        raise PolicyInvalid("политика %s: неизвестные ключи верхнего уровня: %s "
                            "(допустимы: %s)"
                            % (path, _names(unknown),
                               ", ".join(POLICY_TOP_KEYS)))
    missing = [k for k in POLICY_TOP_KEYS if k not in raw]
    if missing:
        raise PolicyInvalid(
            "политика %s не объявляет: %s. Политика задаётся целиком: "
            "недостающие поля НЕ достраиваются умолчаниями, иначе пакет "
            "объявлял бы одно, а ядро применяло другое."
            % (path, ", ".join(missing)))

    ceiling = raw["ceiling"]
    # bool — подкласс int: True прошёл бы как потолок 1.
    if isinstance(ceiling, bool) or not isinstance(ceiling, int):
        raise PolicyInvalid("политика %s: ceiling должен быть целым числом" % path)
    if ceiling < 1:
        raise PolicyInvalid("политика %s: ceiling должен быть не меньше 1, "
                            "получено %d" % (path, ceiling))
    if ceiling > CONTRACT_MAX_FINDINGS:
        raise PolicyInvalid(
            "политика %s: ceiling %d превышает потолок контракта %d "
            "(contracts/review-result.schema.json, findings.maxItems). "
            "Результат с таким числом замечаний приложение забракует, "
            "поэтому пакет отвергается здесь, а не молча обрезается."
            % (path, ceiling, CONTRACT_MAX_FINDINGS))

    bias = raw["bias"]
    if bias not in POLICY_BIAS_VALUES:
        raise PolicyInvalid("политика %s: bias должен быть одним из %s, "
                            "получено %r"
                            % (path, ", ".join(POLICY_BIAS_VALUES), bias))

    prompt = raw["prompt"]
    if not isinstance(prompt, dict):
        raise PolicyInvalid("политика %s: prompt должен быть словарём" % path)
    unknown = set(prompt) - set(POLICY_PROMPT_KEYS)
    if unknown:
        # Опечатка в ключе иначе означала бы, что в промпт молча ушёл текст
        # по умолчанию, а автор пакета уверен, что применил свой.
        raise PolicyInvalid("политика %s: неизвестные ключи prompt: %s"
                            % (path, _names(unknown)))
    missing = [k for k in POLICY_PROMPT_KEYS if k not in prompt]
    if missing:
        raise PolicyInvalid("политика %s: prompt не объявляет: %s"
                            % (path, ", ".join(missing)))
    texts = {}
    for key in POLICY_PROMPT_KEYS:
        value = prompt[key]
        if not isinstance(value, str) or not value.strip():
            raise PolicyInvalid("политика %s: prompt.%s должен быть непустой "
                                "строкой" % (path, key))
        texts[key] = value.strip()

    verification = raw["verification"]
    if not isinstance(verification, dict):
        raise PolicyInvalid("политика %s: verification должен быть словарём" % path)
    unknown = set(verification) - set(POLICY_VERIFICATION_KEYS)
    if unknown:
        raise PolicyInvalid("политика %s: неизвестные ключи verification: %s"
                            % (path, _names(unknown)))
    missing = [k for k in POLICY_VERIFICATION_KEYS if k not in verification]
    if missing:
        raise PolicyInvalid("политика %s: verification не объявляет: %s"
                            % (path, ", ".join(missing)))
    mode = verification["mode"]
    if mode not in POLICY_VERIFICATION_MODES:
        raise PolicyInvalid("политика %s: verification.mode должен быть одним "
                            "из %s, получено %r"
                            % (path, ", ".join(POLICY_VERIFICATION_MODES), mode))
    batch = verification["batch_size"]
    if isinstance(batch, bool) or not isinstance(batch, int) or batch < 1:
        raise PolicyInvalid("политика %s: verification.batch_size должен быть "
                            "целым числом не меньше 1" % path)

    return {"ceiling": ceiling, "bias": bias, "prompt": texts,
            "verification": {"mode": mode, "batch_size": batch}}


def _sev_rank(f):
    """Класс защиты от бюджета: 0 — не режем (critical и high), дальше по убыванию.
    critical и high в ОДНОМ классе намеренно: docreview._rank_union считает
    защищёнными именно ранг 0, и развести их значило бы снять защиту с high."""
    return {"critical": 0, "high": 0, "medium": 1, "low": 2}.get(
        f.get("severity", "medium"), 1)


# Вес важности внутри класса: critical выше high, чтобы при равном согласии
# проходов он шёл первым в выдаче. Значения словаря SEVERITIES покрыты полностью —
# иначе новое значение молча получало бы вес medium.
_SEV_WEIGHT = {"critical": 4, "high": 3, "medium": 2, "low": 1,
               "clarification": 1}


def _priority(f):
    """Важность × согласие проходов — вес для ранжирования.

    ВАЖНО про имя: это НЕ поле `confidence` из выдачи. Раньше и код,
    и комментарии называли обе величины «уверенностью», хотя считаются
    они по-разному и служат разному:

      * здесь — `severity` × `merged_count`, вес «показать выше»;
      * `docreview._confidence` — откалиброванная доля попаданий,
        поле выдачи, в ранжировании НЕ участвует вовсе.

    Склейка этих понятий и была причиной того, что надбавка за согласие
    проходов попала в показатель достоверности и испортила его калибровку
    (docs/confidence-calibration.md).

    Произведение (а не строгий приоритет severity) позволяет многократно
    подтверждённому low обойти едва замеченный medium — пропуск реального
    дефекта хуже придирки. Содержательность цитаты — тай-брейк."""
    sev = _SEV_WEIGHT.get(f.get("severity", "medium"), 2)
    return (sev * f.get("merged_count", 1), content_score(f))


def apply_budget(kept, ceiling=BUDGET_CEILING):
    """Ранжирование и отсечение при переполнении бюджета.

    high НЕ режется никогда: сначала берём все high-замечания, затем добираем
    medium/low по убыванию важность × согласие проходов до потолка. Если одних high
    больше потолка — оставляем их все (полнота важных дефектов приоритетнее
    бюджета). При наборе в пределах потолка возвращаем вход без изменений.
    Возвращает (оставленные, отсечённые).
    """
    if len(kept) <= ceiling:
        return kept, []
    high = [f for f in kept if _sev_rank(f) == 0]
    rest = [f for f in kept if _sev_rank(f) != 0]
    # Внутри защищённого класса тоже упорядочиваем по важности: там лежат
    # и critical, и high, и без сортировки critical оказывался ниже high
    # просто по порядку поступления.
    high.sort(key=lambda f: _priority(f), reverse=True)
    rest.sort(key=lambda f: _priority(f), reverse=True)
    slots = max(0, ceiling - len(high))
    # Защищённые впереди (не режутся), затем rest по важность × согласие проходов.
    # Финальную пересортировку по severity НЕ делаем — она бы отменила ранг.
    keep = high + rest[:slots]
    dropped = rest[slots:]
    return keep, dropped


def ask_verifier(prompt):
    """Вызов модели для верификации. Отдельно от ask_model: своя схема ответа.

    num_predict меньше, чем у поиска: вердикт с короткой причиной на два
    десятка кандидатов укладывается в этот бюджет, а лишний запас — это
    лишние секунды на демонстрации.
    """
    # Сбой верификатора НЕ уносит уже найденные замечания.
    #
    # Это прямое требование: 05.09 отдельной правкой добивались, чтобы при
    # отказе модели результат не терялся, — а верификатор, брошенный наружу
    # как ModelUnavailable, отменял бы уже выполненные проходы поиска.
    # Замечания, оставшиеся без суждения, помечаются `not_verified`,
    # и в enforcing они НЕ отбрасываются: молчание верификатора — не приговор.
    # Тот же принцип распространяется на фолбек: он лишь даёт вторую попытку,
    # а если и она не вышла, поведение ровно такое, как без него.
    try:
        return chat(prompt, VERDICT_SCHEMA, 2048)
    except requests.exceptions.RequestException as e:
        print("  !! верификатор недоступен (%s), партия без вердикта" % e,
              file=sys.stderr)
        return []
    except (json.JSONDecodeError, KeyError, ValueError):
        print("  !! верификатор вернул невалидный json, партия пропущена",
              file=sys.stderr)
        return []


def _verdict_index(raw, size):
    """Номер кандидата из ответа верификатора, или None.

    Модель возвращает id то числом, то строкой, изредка с точкой («3.»).
    Разбирать это здесь дешевле, чем терять вердикт: потерянный вердикт
    в enforcing-режиме означает, что замечание останется непроверенным
    и тихо пройдёт как принятое.
    """
    if isinstance(raw, bool):
        return None
    if isinstance(raw, int):
        idx = raw
    elif isinstance(raw, str):
        # Строго число, допустима одна завершающая точка («3.»). Прежний
        # вариант вычищал все нецифровые символы, и тогда "-1" становилось
        # первым кандидатом, а "1e2" — двенадцатым: вердикт привязывался
        # к чужому замечанию и в enforcing удалял именно его.
        m = re.fullmatch(r"\s*(\d+)\.?\s*", raw)
        if not m:
            return None
        idx = int(m.group(1))
    else:
        return None
    return idx - 1 if 1 <= idx <= size else None


def verify_semantics(findings, doc_text, policy=None, batch_size=None):
    """Semantic verdict: второе мнение по каждому замечанию.

    Возвращает те же находки с полем `_verdict` = {"verdict", "reason"}.
    НИЧЕГО не отбрасывает: решение об отсечении принимает вызывающий по
    политике пакета. Разделено намеренно — слой, который сам решает, что
    показать, невозможно замерить отдельно от того, что он меняет.

    Замечания группируются по фрагменту документа: верификатору нужен
    контекст цитаты, а подавать документ целиком на каждое замечание —
    это и окно модели, и время. На двадцати замечаниях выходит две-три
    партии вместо двадцати вызовов.
    """
    policy = DEFAULT_POLICY if policy is None else policy
    if not findings:
        return findings
    size = batch_size or policy.get("verification", {}).get(
        "batch_size", DEFAULT_VERIFICATION["batch_size"])

    fragments = split_document(doc_text)
    # Каждой находке — фрагмент, в котором лежит её цитата. Не нашлось
    # (цитата собрана кросс-фрагментным проходом) — весь документ.
    by_fragment = {}
    for f in findings:
        quote = (f.get("quote") or "").strip()
        head = quote.split("\n", 1)[0]
        idx = next((i for i, fr in enumerate(fragments) if head and head in fr),
                   None)
        by_fragment.setdefault(idx, []).append(f)

    checked, conflicts = 0, 0
    for idx, group in by_fragment.items():
        context = fragments[idx] if idx is not None else doc_text
        for start in range(0, len(group), size):
            batch = group[start:start + size]
            listing = "\n\n".join(
                "%d. Тип: %s\n   Цитата: «%s»\n   Объяснение: %s"
                % (i + 1, f.get("defect_id", "?"), (f.get("quote") or "").strip(),
                   (f.get("explanation") or "").strip())
                for i, f in enumerate(batch))
            verdicts = ask_verifier(PROMPT_VERIFY.format(
                candidates=listing, fragment=context))
            seen = set()
            for item in verdicts if isinstance(verdicts, list) else []:
                if not isinstance(item, dict):
                    continue
                pos = _verdict_index(item.get("id"), len(batch))
                if pos is None:
                    continue
                verdict = item.get("verdict")
                if verdict not in ("accept", "reject"):
                    continue
                if pos in seen:
                    # Повторный id в одной партии: раньше выигрывал последний,
                    # а счётчик рос дважды — противоречивый дубликат мог
                    # перевернуть решение, статистика показывала больше
                    # проверенных, чем есть замечаний, а кандидат, чей id
                    # модель пропустила, оставался незамеченным.
                    # Оставляем первый вердикт и говорим о конфликте вслух.
                    conflicts += 1
                    continue
                seen.add(pos)
                batch[pos]["_verdict"] = {
                    "verdict": verdict,
                    "reason": (item.get("reason") or "").strip()[:200],
                }
                checked += 1

    rejected = sum(1 for f in findings
                   if (f.get("_verdict") or {}).get("verdict") == "reject")
    # Непроверенные считаем и печатаем: молчаливый пропуск означал бы, что
    # в enforcing-режиме часть замечаний проходит вообще без суждения.
    print(f"[verify] проверено {checked} из {len(findings)}, "
          f"отклонено {rejected}, без вердикта {len(findings) - checked}"
          + (f", повторных id отброшено {conflicts}" if conflicts else ""))
    return findings


def run_full(doc_text, defects, taxonomy_text, valid_ids, known_objects,
             frag_mode="dict", glossary_text=None, conventions_text="",
             label="full", policy=None):
    """
    Продуктовый режим: проход по фрагментам плюс проход по документу
    целиком, затем дедупликация.

    frag_mode задаёт промпт прохода по фрагментам. Глобальный проход
    намеренно НЕ параметризован и всегда идёт на замороженной константе
    GLOSSARY: тогда разница между full и full2 объясняется только
    изменением промпта фрагментов, а не двумя правками сразу.

    policy — политика приёмки из Review Pack (run_review.load_policy).
    Она задаёт и ориентиры объёма в промптах, и потолок выдачи, поэтому
    протягивается в оба прохода и в apply_budget: разъехавшись, эти три
    места дали бы промпт, просящий у модели больше, чем потолок пропустит.
    """
    policy = DEFAULT_POLICY if policy is None else policy
    frag = run(doc_text, frag_mode, taxonomy_text, valid_ids, known_objects,
               glossary_text=glossary_text, conventions_text=conventions_text,
               policy=policy)
    glob = run_global(doc_text, defects, GLOSSARY, policy=policy)

    # Детерминированные типы принадлежат формальному слою (check_formal): он их
    # ловит точнее и без галлюцинаций. Находки этих типов из модели отбрасываем,
    # чтобы не было межслойного дубля и модельных ложных срабатываний.
    det_ids = {d["id"] for d in defects
               if d.get("detectable_by") == "deterministic"}
    combined = [f for f in (frag["findings"] + glob["findings"])
                if f.get("defect_id") not in det_ids]
    kept, merged = dedupe(combined, doc_text)

    # Semantic verdict — ДО бюджета, а не после. Бюджет отбирает по важности
    # среди принятых, и проверять уже отобранное значило бы оставить срезанное
    # непроверенным, а освободившиеся места — незанятыми: отвергнутое
    # замечание должно уступить место следующему, а не просто исчезнуть.
    verification = policy.get("verification", DEFAULT_VERIFICATION)
    vmode = verification.get("mode", "advisory")
    rejected_by_verifier = []
    if vmode != "off" and kept:
        kept = verify_semantics(kept, doc_text, policy=policy)
        if vmode == "enforcing":
            rejected_by_verifier = [
                f for f in kept
                if (f.get("_verdict") or {}).get("verdict") == "reject"]
            kept = [f for f in kept if f not in rejected_by_verifier]

    kept, capped = apply_budget(kept, ceiling=policy["ceiling"])

    print(f"[{label}] до дедупликации {len(combined)}, после дедупа "
          f"{len(kept) + len(capped) + len(rejected_by_verifier)}, "
          f"склеено {len(merged)}, "
          f"отклонено верификатором {len(rejected_by_verifier)}, "
          f"отсечено бюджетом {len(capped)}, итог {len(kept)}")

    return {
        "mode": label,
        "fragments": frag["fragments"],
        "total_seconds": round(frag["total_seconds"] + glob["total_seconds"], 1),
        "found_raw": frag["found_raw"] + glob["found_raw"],
        "verified": len(kept),
        "before_dedupe": len(combined),
        "merged_away": len(merged),
        "capped_away": len(capped),
        "rejected_count": frag["rejected_count"] + glob["rejected_count"],
        "reject_reasons": {**frag["reject_reasons"], **glob["reject_reasons"]},
        # Сколько символов не поместилось в кросс-фрагментный проход.
        # Ноль — документ прошёл целиком.
        "truncated_chars": glob.get("truncated_chars", 0),
        "severity_fixed": sum(1 for f in kept if "severity_raw" in f),
        # Замер слоя верификации: сколько получило вердикт и сколько отвергнуто.
        # Считается и в advisory, где выдача не меняется, — иначе цену
        # включения enforcing не на чем оценить.
        "verified_count": sum(1 for f in kept + rejected_by_verifier
                              if f.get("_verdict")),
        "verifier_rejected": len(rejected_by_verifier),
        "verifier_would_reject": sum(
            1 for f in kept if (f.get("_verdict") or {}).get("verdict") == "reject"),
        "findings": kept,
        "merged": merged,
        "capped": capped,
        "verifier_dropped": rejected_by_verifier,
        "rejected": frag["rejected"] + glob["rejected"],
    }


def summarize(res):
    raw, ver = res["found_raw"], res["verified"]
    share = f"{ver / raw * 100:.0f}%" if raw else "—"
    print(f"\n=== {res['mode']} ===")
    print(f"  фрагментов:         {res['fragments']}")
    print(f"  замечаний выдано:   {raw}")
    if "before_dedupe" in res:
        print(f"  до дедупликации:    {res['before_dedupe']}")
        print(f"  склеено дублей:     {res['merged_away']}")
    print(f"  принято:            {ver} ({share})")
    print(f"  отброшено:          {res['rejected_count']}")
    if res.get("severity_fixed"):
        print(f"  важность исправлена: {res['severity_fixed']} "
              f"(модель вернула значение вне словаря)")
    for k, v in sorted(res["reject_reasons"].items(), key=lambda x: -x[1]):
        print(f"      {k}: {v}")
    print(f"  время:              {res['total_seconds']} с")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--doc", required=True)
    ap.add_argument("--defects", default="defects.yaml")
    ap.add_argument("--glossary", default="glossary.yaml")
    ap.add_argument("--mode", default="dict",
                    choices=["baseline", "taxonomy", "dict", "global",
                             "full", "dict2", "full2", "all", "v2"])
    ap.add_argument("--out", default="results")
    args = ap.parse_args()

    doc_text = Path(args.doc).read_text(encoding="utf-8")
    taxonomy_text, valid_ids, defects = load_taxonomy(args.defects)
    known_objects = extract_known_objects(doc_text)
    terms_text, conventions_text = load_glossary(args.glossary)

    print(f"Объектов в словаре: {len(known_objects.splitlines())}")
    print(f"Терминов в глоссарии: {len(terms_text.splitlines())}, "
          f"соглашений: {len(conventions_text.splitlines())}")

    if args.mode == "all":
        modes = ["baseline", "taxonomy", "dict", "global", "full"]
    elif args.mode == "v2":
        modes = ["dict2", "full2"]
    else:
        modes = [args.mode]

    outdir = Path(args.out)
    outdir.mkdir(exist_ok=True)

    results = []
    for m in modes:
        if m == "global":
            res = run_global(doc_text, defects, GLOSSARY)
        elif m == "full":
            res = run_full(doc_text, defects, taxonomy_text,
                           valid_ids, known_objects)
        elif m == "full2":
            res = run_full(doc_text, defects, taxonomy_text,
                           valid_ids, known_objects,
                           frag_mode="dict2",
                           glossary_text=terms_text,
                           conventions_text=conventions_text,
                           label="full2")
        elif m == "dict2":
            res = run(doc_text, m, taxonomy_text, valid_ids, known_objects,
                      glossary_text=terms_text,
                      conventions_text=conventions_text)
        else:
            res = run(doc_text, m, taxonomy_text, valid_ids, known_objects)
        results.append(res)
        path = outdir / f"{Path(args.doc).stem}_{m}.json"
        path.write_text(json.dumps(res, ensure_ascii=False, indent=2),
                        encoding="utf-8")
        print(f"  сохранено: {path}")

    for r in results:
        summarize(r)

    print("\n  Дальше: python3 mark_findings.py --doc "
          f"{Path(args.doc).stem} --modes {','.join(modes)}")


if __name__ == "__main__":
    main()
