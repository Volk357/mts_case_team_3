#!/bin/sh
# Резервная копия DocReview: база и загруженные документы.
#
# Зачем: в базе лежит не только состояние сервиса, но и собранная разметка —
# оценки замечаний, единственный источник доли полезных. Восстановить её
# неоткуда: документы можно загрузить заново, разметку — нет.
#
# Установка и расписание описаны в DEPLOY.md, раздел «Резервное копирование».
set -eu

DEST=${DOCREVIEW_BACKUP_DIR:-/opt/docreview/backups}
KEEP=${DOCREVIEW_BACKUP_KEEP:-14}
STAMP=$(date +%Y-%m-%d-%H%M)

mkdir -p "$DEST"

# Один прогон за раз. Параллельные копии не нужны, а вреда от них хватает:
# имя комплекта имеет точность до минуты, и второй прогон в ту же минуту
# вложил бы свой каталог внутрь уже опубликованного. Блокировка снимает и
# это, и лишнюю нагрузку на базу от одновременных дампов.
LOCK="$DEST/.backup.lock"
if command -v flock > /dev/null 2>&1; then
    exec 9> "$LOCK"
    if ! flock -n 9; then
        echo "$(date -Is) пропуск: другой прогон резервного копирования ещё идёт"
        exit 0
    fi
fi

# Комплект за эту минуту уже опубликован — второй раз не переписываем.
if [ -e "$DEST/$STAMP" ]; then
    echo "$(date -Is) пропуск: комплект $STAMP уже существует"
    exit 0
fi

# Пишем во временные файлы и переименовываем только после того, как обе части
# сняты и дамп прочитан. Иначе сбой на середине оставил бы неполный комплект,
# внешне неотличимый от удачного, — и его нашли бы в тот момент, когда он нужен.
# Комплект собирается во временном каталоге и публикуется ОДНИМ
# переименованием. Дамп и архив бесполезны по отдельности: дамп восстановит
# записи, ссылающиеся на отсутствующие файлы. Два отдельных переименования
# оставляли бы окно, в котором на диске лежит половина комплекта под
# финальным именем — внешне неотличимая от целой.
# В имя входит PID: два запуска в одну минуту (ручной и по расписанию) иначе
# писали бы в один каталог и удаляли его друг у друга.
STAGE="$DEST/.staging-$STAMP-$$"
cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT INT TERM
rm -rf "$STAGE"
mkdir -p "$STAGE"

sudo -u postgres pg_dump -Fc docreview > "$STAGE/docreview.dump"

# Документы: без них дамп восстановит записи, ссылающиеся на пустоту.
tar czf "$STAGE/documents.tar.gz" -C /opt/docreview/data documents

# Проверяем, что дамп читается, а не только создался: битый бэкап хуже, чем
# его отсутствие, потому что на него рассчитывают.
sudo -u postgres pg_restore --list "$STAGE/docreview.dump" > /dev/null

mv "$STAGE" "$DEST/$STAMP"
trap - EXIT INT TERM

# Незавершённые комплекты от прошлых сбоев не должны копиться.
# Чужой staging не трогаем моложе суток: он может принадлежать идущему прогону.
find "$DEST" -maxdepth 1 -name '.staging-*' -mtime +1 -exec rm -rf {} +
find "$DEST" -maxdepth 1 -type d -name '20*' -mtime +"$KEEP" -exec rm -rf {} +

echo "$(date -Is) ok: $DEST/$STAMP ($(du -sh "$DEST/$STAMP" | cut -f1))"
